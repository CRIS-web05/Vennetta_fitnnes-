export const getTranslation = (locale, section) => {
  const code = typeof locale === 'string' ? locale : (locale?.code || 'es');
  const currentLang = translations[code] || translations.en || translations.es;
  const enLang = translations.en || {};
  const esLang = translations.es || {};

  if (!section) {
    return { ...esLang, ...enLang, ...currentLang };
  }

  const esSection = esLang[section] || {};
  const enSection = enLang[section] || {};
  const currentSection = currentLang[section] || {};

  return {
    ...esSection,
    ...enSection,
    ...currentSection,
  };
};

export default translations;
